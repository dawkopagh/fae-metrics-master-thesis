r"""render_results_tables.py — Emit LaTeX table fragments for Chapter 4 (local).

LOCAL post-processing script (venv, NOT Colab). Reads the result CSVs under
results/ and writes booktabs-style \input-able LaTeX fragments into
Latex/tables/. Each fragment is a complete float (table/tabularx) carrying the
SAME \caption and \label that chapter4_state_observers.tex already defines, so
Chapter 4 can replace its inline [pending full run] tables with a single
\input{tables/<name>}.

Fragments produced (filename -> \label it carries):
    redundancy_resnet.tex   -> tab:redundancy-resnet
    redundancy_squeeze.tex  -> tab:redundancy-squeeze
    meta.tex                -> tab:meta
    ranking_resnet.tex      -> tab:ranking-resnet
    ranking_squeeze.tex     -> tab:ranking-squeeze
    rank_stability.tex      -> tab:rank-stability
    ensemble.tex            -> tab:ensemble
    friedman.tex            -> tab:friedman
    wilcoxon.tex            -> tab:wilcoxon

Every fragment is generated from whatever CSVs are present; missing inputs
yield a fragment whose cells read \texttt{[pending full run]} so the chapter
still compiles. The script runs identically on the 12-image PILOT CSVs (the
defaults) and on the 600-image FULL CSVs (pass the *_FULL / *_600 paths).

Exact command (the defaults under results/ ARE the authoritative full-run
CSVs; only the redundancy caption note needs to be passed):

    fae-metrics-master-thesis/.venv/bin/python \
        fae-metrics-master-thesis/experiments/render_results_tables.py \
        --n-images-label "full run, 600 images"
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

_REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_REPO))

from src.metrics.redundancy import (  # noqa: E402
    METRIC_CATEGORIES,
    category_redundancy_summary,
)

_RESULTS = _REPO.parent / "results"
_TABLES_DIR = _REPO.parent / "Latex" / "tables"

_PENDING = r"\texttt{[pending]}"

# M* metric set carried into aggregation (mirrors compare_rankings.py).
_M_STAR = [
    "faithfulness_correlation",
    "max_sensitivity",
    "pixel_flipping",
    "pointing_game",
    "random_logit",
    "relevance_mass_accuracy",
    "sparseness",
]

_FAE_ORDER = [
    "integrated_gradients", "saliency", "gradcam", "guided_backprop",
    "deep_lift", "lrp", "occlusion",
]

_SCHEME_COLS = {
    "uniform": "effectiveness_uniform",
    "autoweighted": "effectiveness_autoweighted",
    "mqdiscount": "effectiveness_mqdiscount",
    "single_fc": "effectiveness_single_fc",
}


# ---------------------------------------------------------------------------
# Small LaTeX helpers
# ---------------------------------------------------------------------------

def _esc(s: str) -> str:
    """Escape underscores for LaTeX text mode."""
    return str(s).replace("_", r"\_")


def _fmt(x, nd: int = 3) -> str:
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return _PENDING
    try:
        return f"{float(x):.{nd}f}"
    except (TypeError, ValueError):
        return _esc(str(x))


def _read(path: Path) -> pd.DataFrame | None:
    if path.exists():
        return pd.read_csv(path)
    return None


def _write(name: str, body: str) -> None:
    _TABLES_DIR.mkdir(parents=True, exist_ok=True)
    out = _TABLES_DIR / name
    header = (
        "% Auto-generated by experiments/render_results_tables.py — do not edit.\n"
        "% Regenerate after each run; \\input this file from "
        "chapter4_state_observers.tex.\n"
    )
    out.write_text(header + body.rstrip() + "\n")
    print(f"  wrote {out}")


# ---------------------------------------------------------------------------
# Redundancy summary tables (tab:redundancy-resnet / tab:redundancy-squeeze)
# ---------------------------------------------------------------------------

def _redundancy_fragment(matrix: pd.DataFrame | None, model_label: str,
                         label: str, n_images: str) -> str:
    rows_tex: list[str] = []
    if matrix is not None and not matrix.empty:
        summary = category_redundancy_summary(matrix, METRIC_CATEGORIES)
        summary = summary.sort_values("mean_abs_rho", ascending=False)
        for cat, row in summary.iterrows():
            n_m = int(row["n_metrics"])
            rho = row["mean_abs_rho"]
            # A single-metric category has no within-category pair, so the
            # mean |rho| is undefined (n/a), not a pending/TODO value.
            rho_str = (r"\textit{n/a}" if n_m < 2
                       or not np.isfinite(rho) else _fmt(rho))
            rows_tex.append(f"{cat} & {n_m} & {rho_str} \\\\")
    if not rows_tex:
        rows_tex = [f"{c} & 2 & {_PENDING} \\\\"
                    for c in ["Complexity", "Robustness", "Randomization",
                              "Localization", "Faithfulness"]]
    body = "\n".join(rows_tex)
    return rf"""\begin{{table}}[H]
\centering
\caption{{Redundancy summary --- {model_label}: within-category mean $|\rho|$ at
the $|\rho| > 0.85$ pruning threshold ({n_images}).}}
\begin{{tabularx}}{{\linewidth}}{{lcc}}
\toprule
Category & $n$ metrics & Mean $|\rho|$ \\
\midrule
{body}
\bottomrule
\end{{tabularx}}
\label{{{label}}}
\end{{table}}"""


# ---------------------------------------------------------------------------
# Meta-evaluation table (tab:meta)
# ---------------------------------------------------------------------------

def _meta_na(x, nd: int = 3) -> str:
    """Like ``_fmt`` but NaN renders as ``n/a`` (a real missing cell, not a TODO)."""
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return r"\textit{n/a}"
    return _fmt(x, nd)


def _meta_fragment(rel: pd.DataFrame | None) -> str:
    rows_tex: list[str] = []
    agg = None
    if rel is not None and not rel.empty:
        comp = rel[rel.get("status", "completed") == "completed"] \
            if "status" in rel.columns else rel
        agg = (
            comp.groupby("metric")[["nr_score", "ar_score",
                                    "combined_reliability", "runtime_seconds"]]
            .mean()
        )
    for metric in _M_STAR:
        if agg is not None and metric in agg.index:
            r = agg.loc[metric]
            rows_tex.append(
                f"{_esc(metric)} & {_meta_na(r['nr_score'])} & {_meta_na(r['ar_score'])} & "
                f"{_meta_na(r['combined_reliability'])} & {_fmt(r['runtime_seconds'], 1)} \\\\"
            )
        else:
            rows_tex.append(
                f"{_esc(metric)} & {_PENDING} & {_PENDING} & {_PENDING} & {_PENDING} \\\\"
            )
    body = "\n".join(rows_tex)
    return rf"""\begin{{table}}[H]
\centering
\caption{{Metric reliability from MetaQuantus (NR, AR, combined), averaged over
(model, FAE) cells. Cells marked \textit{{n/a}} are metrics whose Adversarial
Reactivity could not be scored in this run (the \texttt{{explain\_func}}-based
perturbation failed), so no combined reliability is available.}}
\begin{{tabularx}}{{\linewidth}}{{lcccc}}
\toprule
Metric & NR & AR & Combined $r_k$ & Mean runtime (s) \\
\midrule
{body}
\bottomrule
\end{{tabularx}}
\label{{tab:meta}}
\end{{table}}"""


# ---------------------------------------------------------------------------
# Ranking tables (tab:ranking-resnet / tab:ranking-squeeze)
# ---------------------------------------------------------------------------

def _ranking_fragment(ranking: pd.DataFrame | None, model: str,
                      model_label: str, label: str) -> str:
    means = None
    if ranking is not None and not ranking.empty:
        sub = ranking[ranking["model"] == model]
        if not sub.empty:
            means = sub.groupby("fae_method")[list(_SCHEME_COLS.values())].mean()
    rows_tex: list[str] = []
    for fae in _FAE_ORDER:
        if means is not None and fae in means.index:
            r = means.loc[fae]
            rows_tex.append(
                f"{_esc(fae)} & {_fmt(r['effectiveness_uniform'])} & "
                f"{_fmt(r['effectiveness_autoweighted'])} & "
                f"{_fmt(r['effectiveness_mqdiscount'])} & "
                f"{_fmt(r['effectiveness_single_fc'])} \\\\"
            )
        else:
            rows_tex.append(
                f"{_esc(fae)} & {_PENDING} & {_PENDING} & {_PENDING} & {_PENDING} \\\\"
            )
    body = "\n".join(rows_tex)
    return rf"""\begin{{table}}[H]
\centering
\caption{{Mean effectiveness index $E(\Phi)$ per FAE method under each weighting
scheme ({model_label}, averaged over test images).}}
\begin{{tabularx}}{{\linewidth}}{{lcccc}}
\toprule
FAE method & Uniform & Autoweighted & MQ-discount & Single-FC \\
\midrule
{body}
\bottomrule
\end{{tabularx}}
\label{{{label}}}
\end{{table}}"""


# ---------------------------------------------------------------------------
# Rank-stability table (tab:rank-stability)
# ---------------------------------------------------------------------------

def _rank_stability_fragment(ranking: pd.DataFrame | None) -> str:
    from scipy.stats import spearmanr

    pairs = [
        ("Uniform vs.\\ AW", "effectiveness_uniform", "effectiveness_autoweighted"),
        ("Uniform vs.\\ MQ", "effectiveness_uniform", "effectiveness_mqdiscount"),
        ("AW vs.\\ MQ", "effectiveness_autoweighted", "effectiveness_mqdiscount"),
        ("Single-FC vs.\\ MQ", "effectiveness_single_fc", "effectiveness_mqdiscount"),
    ]

    def _rho_row(model: str) -> list[str]:
        cells: list[str] = []
        if ranking is None or ranking.empty:
            return [_PENDING] * len(pairs)
        sub = ranking[ranking["model"] == model]
        if sub.empty:
            return [_PENDING] * len(pairs)
        means = sub.groupby("fae_method")[list(_SCHEME_COLS.values())].mean()
        for _, ca, cb in pairs:
            if len(means) >= 2:
                rho, _p = spearmanr(means[ca], means[cb])
                cells.append(_fmt(rho))
            else:
                cells.append(_PENDING)
        return cells

    def _inv_row() -> list[str]:
        # # discordant FAE pairs between each scheme pair, summed over models.
        if ranking is None or ranking.empty:
            return [_PENDING] * len(pairs)
        cells: list[str] = []
        for _, ca, cb in pairs:
            total = 0
            ok = False
            for model in ranking["model"].unique():
                sub = ranking[ranking["model"] == model]
                means = sub.groupby("fae_method")[list(_SCHEME_COLS.values())].mean()
                if len(means) < 2:
                    continue
                ok = True
                ra = means[ca].rank(ascending=False, method="min")
                rb = means[cb].rank(ascending=False, method="min")
                idx = list(means.index)
                for i in range(len(idx)):
                    for j in range(i + 1, len(idx)):
                        a, b = idx[i], idx[j]
                        if np.sign(ra[a] - ra[b]) != np.sign(rb[a] - rb[b]):
                            total += 1
            cells.append(str(total) if ok else _PENDING)
        return cells

    rn = _rho_row("resnet18")
    sq = _rho_row("squeezenet")
    inv = _inv_row()
    body = (
        "Spearman rank corr.\\ (ResNet-18)  & " + " & ".join(rn) + " \\\\\n"
        "Spearman rank corr.\\ (SqueezeNet) & " + " & ".join(sq) + " \\\\\n"
        "\\# rank inversions                & " + " & ".join(inv) + " \\\\"
    )
    return rf"""\begin{{table}}[H]
\centering
\caption{{Induced FAE-method ranks under each weighting scheme, and
rank-stability summary (Spearman rank correlation between per-method mean-$E$
rankings; rank inversions summed over both models).}}
\begin{{tabularx}}{{\linewidth}}{{lcccc}}
\toprule
Comparison & Uniform vs.\ AW & Uniform vs.\ MQ & AW vs.\ MQ & Single-FC vs.\ MQ \\
\midrule
{body}
\bottomrule
\end{{tabularx}}
\label{{tab:rank-stability}}
\end{{table}}"""


# ---------------------------------------------------------------------------
# Ensemble table (tab:ensemble)
# ---------------------------------------------------------------------------

def _ensemble_n_per_model(ensemble: pd.DataFrame | None) -> str:
    """Human-readable per-model image count for captions (e.g. ``$n=600$``)."""
    if ensemble is None or ensemble.empty:
        return r"$n$ pending"
    counts = sorted(ensemble.groupby("model")["image_id"].nunique().unique())
    if len(counts) == 1:
        return f"$n={counts[0]}$"
    return "/".join(f"$n={c}$" for c in counts)


def _ensemble_fragment(ensemble: pd.DataFrame | None) -> str:
    """Aggregate individual_vs_ensemble.csv per model.

    Columns: model, image_id, eff_ensemble, eff_individual_mean,
    eff_individual_best. Per model we average each effectiveness column over
    all images present in the CSV and report Delta = ensembled - best
    individual. The caption's per-model n is derived from the CSV itself.
    """
    def _row(model: str, model_label: str) -> str:
        ens_e = best_e = mean_e = None
        if ensemble is not None and not ensemble.empty:
            es = ensemble[ensemble["model"] == model]
            if not es.empty:
                ens_e = float(es["eff_ensemble"].mean())
                best_e = float(es["eff_individual_best"].mean())
                mean_e = float(es["eff_individual_mean"].mean())
        delta = (ens_e - best_e) if (ens_e is not None and best_e is not None) else None
        return (f"{model_label}  & {_fmt(ens_e)} & {_fmt(best_e)} & "
                f"{_fmt(mean_e)} & {_fmt(delta)} \\\\")

    n_label = _ensemble_n_per_model(ensemble)
    body = _row("resnet18", "ResNet-18") + "\n" + _row("squeezenet", "SqueezeNet")
    return rf"""\begin{{table}}[H]
\centering
\caption{{Effectiveness index $E(\Phi)$ of the NormEnsembleXAI-ensembled
attribution against the best and mean individual method, per model (mean over
{n_label} test images per model; ensemble of the six gradient-based methods,
occlusion excluded; all seven $M^{{*}}$ metrics).}}
\begin{{tabularx}}{{\linewidth}}{{lcccc}}
\toprule
Model & Ensembled $E$ & Best individual $E$ & Mean individual $E$ & $\Delta$ (ens.\ $-$ best) \\
\midrule
{body}
\bottomrule
\end{{tabularx}}
\label{{tab:ensemble}}
\end{{table}}"""


# ---------------------------------------------------------------------------
# Friedman table (tab:friedman)
# ---------------------------------------------------------------------------

def _friedman_fragment(stats: pd.DataFrame | None) -> str:
    # statistical_tests.csv schema: model,scheme,friedman_chi2,p_value,
    # significant,critical_difference,n_blocks,n_methods. One row per
    # (model, scheme) present in the CSV.
    _SCHEME_LABELS = {
        "uniform": "Uniform",
        "autoweighted": "Autoweighted",
        "mqdiscount": "MQ-discount",
    }

    def _rows(model: str, model_label: str) -> list[str]:
        out: list[str] = []
        for scheme, scheme_label in _SCHEME_LABELS.items():
            chi = p = sig = None
            if stats is not None and not stats.empty:
                m = stats[(stats["model"] == model)
                          & (stats["scheme"] == scheme)]
                if not m.empty:
                    chi = float(m.iloc[0]["friedman_chi2"])
                    p = float(m.iloc[0]["p_value"])
                    sig = bool(m.iloc[0]["significant"])
                else:
                    continue  # scheme absent from this run's CSV
            sig_str = (_PENDING if sig is None else ("Yes" if sig else "No"))
            out.append(f"{model_label}  & {scheme_label} & {_fmt(chi, 2)} & "
                       f"{_fmt_p(p)} & {sig_str} \\\\")
        return out

    body = "\n".join(_rows("resnet18", "ResNet-18")
                     + _rows("squeezenet", "SqueezeNet"))
    return rf"""\begin{{table}}[H]
\centering
\caption{{Friedman omnibus test over the seven FAE methods, per model and
weighting scheme (blocks are the 600 test images).}}
\begin{{tabularx}}{{\linewidth}}{{llccc}}
\toprule
Model & Weighting & Friedman $\chi^2$ & $p$-value & Significant ($\alpha=0.05$) \\
\midrule
{body}
\bottomrule
\end{{tabularx}}
\label{{tab:friedman}}
\end{{table}}"""


# ---------------------------------------------------------------------------
# Wilcoxon table (tab:wilcoxon)
# ---------------------------------------------------------------------------

def _wilcoxon_fragment(ensemble: pd.DataFrame | None) -> str:
    """Compute paired Wilcoxon from individual_vs_ensemble.csv per model.

    Two paired comparisons per model: ensembled effectiveness vs. the best
    individual method, and vs. the mean individual method (paired per image).
    """
    from src.comparison.statistical_tests import wilcoxon_paired

    def _rows(model: str, model_label: str) -> list[str]:
        out: list[str] = []
        pairs = [
            ("ensemble vs.\\ best individual", "eff_individual_best"),
            ("ensemble vs.\\ mean individual", "eff_individual_mean"),
        ]
        sub = None
        if ensemble is not None and not ensemble.empty:
            sub = ensemble[ensemble["model"] == model]
        for pair_label, col in pairs:
            w = p = sig = None
            if sub is not None and not sub.empty and col in sub.columns:
                res = wilcoxon_paired(
                    sub["eff_ensemble"].to_numpy(), sub[col].to_numpy()
                )
                w = float(res["statistic"])
                p = float(res["p_value"])
                sig = p < 0.05
            sig_str = (_PENDING if sig is None else ("Yes" if sig else "No"))
            out.append(f"{model_label} & {pair_label} & "
                       f"{_fmt(w, 1)} & {_fmt_p(p)} & {sig_str} \\\\")
        return out

    n_label = _ensemble_n_per_model(ensemble)
    body = "\n".join(
        _rows("resnet18", "ResNet-18") + _rows("squeezenet", "SqueezeNet")
    )
    return rf"""\begin{{table}}[H]
\centering
\caption{{Wilcoxon signed-rank test (paired per image, {n_label} per model):
the NormEnsembleXAI-ensembled attribution against the best and the mean
individual method.}}
\begin{{tabularx}}{{\linewidth}}{{llccc}}
\toprule
Model & Pair & $W$ statistic & $p$-value & Significant \\
\midrule
{body}
\bottomrule
\end{{tabularx}}
\label{{tab:wilcoxon}}
\end{{table}}"""


def _fmt_p(p) -> str:
    """Format a p-value compactly (scientific for tiny values)."""
    if p is None or (isinstance(p, float) and not np.isfinite(p)):
        return _PENDING
    p = float(p)
    if p < 1e-3:
        return f"$<10^{{-3}}$"
    return f"{p:.3f}"


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def _parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Render Chapter 4 LaTeX table fragments from result CSVs.",
    )
    p.add_argument("--redundancy-resnet-csv",
                   default=str(_RESULTS / "redundancy_matrix_resnet18.csv"))
    p.add_argument("--redundancy-squeeze-csv",
                   default=str(_RESULTS / "redundancy_matrix_squeezenet.csv"))
    p.add_argument("--reliability-csv",
                   default=str(_RESULTS / "meta_evaluation_reliability.csv"))
    p.add_argument("--ranking-csv",
                   default=str(_RESULTS / "ranking_comparison.csv"))
    p.add_argument("--ensemble-csv",
                   default=str(_RESULTS / "individual_vs_ensemble.csv"))
    p.add_argument("--stats-csv",
                   default=str(_RESULTS / "statistical_tests.csv"))
    p.add_argument("--n-images-label", default="pilot, 12 images",
                   help="Caption note for redundancy tables (e.g. 'full run, 600 images').")
    p.add_argument("--tables-dir", default=str(_TABLES_DIR))
    return p.parse_args()


def main() -> None:
    args = _parse_args()
    global _TABLES_DIR
    _TABLES_DIR = Path(args.tables_dir)

    red_rn = _read(Path(args.redundancy_resnet_csv))
    if red_rn is not None:
        red_rn = red_rn.set_index(red_rn.columns[0])
    red_sq = _read(Path(args.redundancy_squeeze_csv))
    if red_sq is not None:
        red_sq = red_sq.set_index(red_sq.columns[0])
    rel = _read(Path(args.reliability_csv))
    ranking = _read(Path(args.ranking_csv))
    ensemble = _read(Path(args.ensemble_csv))
    stats = _read(Path(args.stats_csv))

    print(f"Writing LaTeX fragments to {_TABLES_DIR}")
    _write("redundancy_resnet.tex",
           _redundancy_fragment(red_rn, "ResNet-18", "tab:redundancy-resnet",
                                args.n_images_label))
    _write("redundancy_squeeze.tex",
           _redundancy_fragment(red_sq, "SqueezeNet~1.1", "tab:redundancy-squeeze",
                                args.n_images_label))
    _write("meta.tex", _meta_fragment(rel))
    _write("ranking_resnet.tex",
           _ranking_fragment(ranking, "resnet18", "ResNet-18", "tab:ranking-resnet"))
    _write("ranking_squeeze.tex",
           _ranking_fragment(ranking, "squeezenet", "SqueezeNet", "tab:ranking-squeeze"))
    _write("rank_stability.tex", _rank_stability_fragment(ranking))
    _write("ensemble.tex", _ensemble_fragment(ensemble))
    _write("friedman.tex", _friedman_fragment(stats))
    _write("wilcoxon.tex", _wilcoxon_fragment(ensemble))
    print("Done.")


if __name__ == "__main__":
    main()
